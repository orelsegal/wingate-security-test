-- התאמה לפי שם מנורמל (חסר סדר, ללא ניקוד/גרשיים) — לא יוצר תלמידים
-- מפתח השוואה: אותיות בלבד, בלי סדר (השמות הפוכים בין המקורות)
create or replace function pg_temp.nkey(t text) returns text
language sql immutable as $fn$
  select coalesce(array_to_string(array(
    select w from unnest(string_to_array(
      regexp_replace(trim(coalesce(t,'')), '[^א-ת0-9 ]', ' ', 'g'), ' ')) as w
    where length(trim(w)) > 0 order by w), ' '), '')
$fn$;

create temp table _norm on commit drop as
  select id, full_name, pg_temp.nkey(full_name) as k from public.students;

create temp table _resolved on commit drop as
select s.*, n.id as student_id, sub.id as subject_id
  from _stage s
  left join _norm n on n.k = pg_temp.nkey(s.target_name)
  left join public.subjects sub on sub.subject_name = s.subject_name;

\echo '── התאמה ──'
select count(*) filter (where student_id is not null and subject_id is not null) as "ייובאו",
       count(*) filter (where student_id is null)  as "תלמיד לא נמצא",
       count(*) filter (where subject_id is null)  as "מקצוע לא נמצא"
  from _resolved;

\echo '── תלמידים שלא נמצאו (לא ייווצרו) ──'
select distinct target_name from _resolved where student_id is null order by 1;
\echo '── מקצועות שלא נמצאו ──'
select distinct subject_name from _resolved where subject_id is null order by 1;

-- כתיבה: השלמה בלבד. COALESCE שומר על ערך קיים; ריק לעולם לא דורס.
insert into public.learning_status
  (student_id, subject_id, ramzor, grades_raw, notes, haliffa, haliffa_notes, source)
select student_id, subject_id, ramzor, grades_raw, notes, haliffa, haliffa_notes, 'import'
  from _resolved
 where student_id is not null and subject_id is not null
on conflict (student_id, subject_id) do update set
  ramzor        = coalesce(excluded.ramzor,        public.learning_status.ramzor),
  grades_raw    = coalesce(excluded.grades_raw,    public.learning_status.grades_raw),
  notes         = coalesce(excluded.notes,         public.learning_status.notes),
  haliffa       = (select array(select distinct unnest(
                     public.learning_status.haliffa || excluded.haliffa))),
  haliffa_notes = coalesce(excluded.haliffa_notes, public.learning_status.haliffa_notes),
  source        = 'import';

\echo '── אימות: סכומי רמזור מול האקסל (צפוי: ירוק 185 · אדום 105 · צהוב 61) ──'
select coalesce(ramzor,'לא הוזן') as רמזור, count(*)
  from public.learning_status group by 1 order by 2 desc;

\echo '── אימות: רשומות לפי מקצוע ──'
select sub.subject_name, count(*) as רשומות,
       count(*) filter (where ls.ramzor is null) as "לא הוזן"
  from public.learning_status ls join public.subjects sub on sub.id = ls.subject_id
 group by 1 order by 2 desc;

\echo '── אימות: תלמידים ותאים ──'
select count(distinct student_id) as תלמידים, count(*) as "רשומות סהכ" from public.learning_status;

\echo '── אימות: ציון מרובה נשמר כלשונו + חליפה רב־ערכית ──'
select s.full_name, sub.subject_name, ls.grades_raw, ls.haliffa, ls.notes
  from public.learning_status ls
  join public.students s on s.id = ls.student_id
  join public.subjects sub on sub.id = ls.subject_id
 where ls.grades_raw like '%,%' or array_length(ls.haliffa,1) > 0
 order by 1 limit 12;

